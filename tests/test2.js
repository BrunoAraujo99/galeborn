const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: { width: 640, height: 360 } });
  const errs = [];
  page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text()); });
  page.on('pageerror', e => errs.push('PAGEERR: ' + e.message + '\n' + e.stack));
  await page.goto('file:///home/claude/duel/dist/galeborn.html');
  await page.waitForTimeout(1500);
  const S = async n => page.screenshot({ path: `/tmp/claude-0/shots/t2_${n}.png` });
  await page.click('#playBtn');
  await page.waitForTimeout(800);
  await page.evaluate(() => __G.beginFight());
  const fps = await page.evaluate(() => new Promise(r => { let n = 0; const t0 = performance.now(); function f() { n++; if (performance.now() - t0 < 1000) requestAnimationFrame(f); else r(n); } requestAnimationFrame(f); }));
  console.log('fps', fps);
  // perfect dodge logic
  const pd = await page.evaluate(() => { const p = __G.player; p.state='move'; p.buf='dash'; p.updMove(0.016, {mx:0,my:0}, new THREE.Vector3(), false); const r = p.tryHit(10, new THREE.Vector3(1,0,0), 'light', p.pos); return r + ' perfect=' + __G.stats.perfect + ' counterT=' + p.counterT.toFixed(2); });
  console.log('dodge:', pd);
  await page.waitForTimeout(300);
  await page.keyboard.press('KeyJ'); await page.waitForTimeout(600); await S('counter');
  console.log('counters', await page.evaluate(() => __G.stats.counters + ' bossHp ' + __G.boss.hp));
  await page.evaluate(() => { const b = __G.boss; b.hp = b.maxHp * 0.49; b.pendingPhase = true; __G.player.hp = 100; });
  await page.waitForTimeout(5000); await S('phase2');
  console.log('phase', await page.evaluate(() => __G.boss.phase + ' ' + __G.boss.state + ' mix ' + World.mix.toFixed(2)));
  await page.evaluate(() => { const b = __G.boss; b.cancelAttack(); b.atk = b.spiral(); b.state = 'attack'; b.at = 0; b.prevAt = -1; __G.player.hp = 100; });
  await page.waitForTimeout(3000); await S('spiral');
  await page.waitForTimeout(4000);
  console.log('after spiral', await page.evaluate(() => __G.boss.state + ' php ' + __G.player.hp));
  await page.evaluate(() => { __G.player.flow = 100; __G.player.hp = 100; __G.player.state='move'; });
  await page.keyboard.press('KeyE');
  await page.waitForTimeout(1500); await S('special_a');
  await page.waitForTimeout(2500); await S('special_b');
  await page.waitForTimeout(4000);
  console.log('after special', await page.evaluate(() => __G.boss.state + ' hp ' + __G.boss.hp + ' pstate ' + __G.player.state + ' bs ' + __G.bossScale.toFixed(2)));
  await page.evaluate(() => { const b = __G.boss; b.cancelAttack(); b.state='idle'; b.posture = 99; b.takeDamage(5, 5, b.chest(), new THREE.Vector3(0,0,1), {}); });
  await page.waitForTimeout(700); await S('break');
  await page.waitForTimeout(1500);
  await page.evaluate(() => { const b = __G.boss; b.hp = 1; b.takeDamage(30, 0, b.chest(), new THREE.Vector3(0,0,1), {big:true}); });
  await page.waitForTimeout(3000); await S('victory_cine');
  await page.waitForTimeout(8000); await S('victory');
  console.log('state', await page.evaluate(() => __G.state));
  await page.keyboard.press('KeyR'); await page.waitForTimeout(1000);
  await page.evaluate(() => __G.beginFight());
  await page.evaluate(() => { __G.player.hp = 5; __G.player.tryHit(10, new THREE.Vector3(1,0,0), 'heavy', __G.player.pos); });
  await page.waitForTimeout(9000); await S('defeat');
  console.log('state', await page.evaluate(() => __G.state));
  console.log('ERRORS:\n' + [...new Set(errs)].slice(0, 30).join('\n'));
  await browser.close();
})();
